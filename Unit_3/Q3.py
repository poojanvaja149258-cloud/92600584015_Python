import math

num1 = 16
num2 = 4.7
num3 = -10

square_root = math.sqrt(num1)
factorial = math.factorial(5)
power = math.pow(2, 3)
absolute = math.fabs(num3)
floor_val = math.floor(num2)
ceil_val = math.ceil(num2)


print("--- Math Module Operations ---")
print(f"Square root of {num1}      : {square_root}")
print(f"Factorial of 5                       : {factorial}")
print(f"2 raised to the power 3    : {power}")
print(f"Absolute value of {num3} : {absolute}")
print(f"Floor value of {num2}  : {floor_val}")
print(f"Ceiling value of {num2} : {ceil_val}")
print(f"Value of Pi (π)  : {math.pi}")
